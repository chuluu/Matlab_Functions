    xn_array(a,:) = xn(floor(1+(N_new*(a-1))):floor(N/Nrecs+(N_new*(a-1)))).*window;
    [Gxx(a,:),~,~,f_Gxx] =  MyPSDX(xn_array(a,:),fs);
